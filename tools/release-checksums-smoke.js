'use strict';

// Byte-level regression test for the release checksum manifest
// (scripts/generate-checksums.mjs). Builds a throwaway dist with two fake
// executables, generates the manifest, and inspects the BYTES: no CR, no
// BOM, LF separators, final LF, 64-hex hashes, sorted names, every hash
// matching its file — then runs the real `sha256sum -c` on the file without
// touching it. Negative controls prove the verifier rejects CRLF, a BOM, a
// wrong hash, a missing record and an unsorted manifest.
//
// Why: release.yml used to build this file through a PowerShell cmdlet that
// writes CRLF on Windows, and every published manifest up to 6.3.3 failed
// `sha256sum -c` with "No such file or directory" on each line.

const fs = require('fs');
const os = require('os');
const path = require('path');
const { spawnSync } = require('child_process');

const ROOT = path.join(__dirname, '..');
let failures = 0;
function check(cond, name) {
  if (cond) { console.log(`  ok  ${name}`); }
  else { console.error(`FAIL  ${name}`); failures++; }
}

// sha256sum: coreutils on Linux/macOS runners; Git for Windows ships it in
// usr/bin. Fail closed if none is found — the whole point is proving the
// published file works with the standard tool.
function findSha256sum() {
  const direct = spawnSync('sha256sum', ['--version'], { encoding: 'utf8' });
  if (!direct.error && direct.status === 0) return { cmd: 'sha256sum', args: [] };
  const candidates = [
    'C:\\Program Files\\Git\\usr\\bin\\sha256sum.exe',
    'C:\\Program Files (x86)\\Git\\usr\\bin\\sha256sum.exe'
  ];
  for (const c of candidates) if (fs.existsSync(c)) return { cmd: c, args: [] };
  return null;
}

(async () => {
  const gen = await import(require('url').pathToFileURL(path.join(ROOT, 'scripts', 'generate-checksums.mjs')).href);

  const dist = fs.mkdtempSync(path.join(os.tmpdir(), 'fixer-checksums-'));
  const fake = {
    '1132-Fixer-Setup-9.9.9.exe': Buffer.from('MZ setup payload ' + 'x'.repeat(4096)),
    '1132-Fixer-Portable-9.9.9.exe': Buffer.from('MZ portable payload ' + 'y'.repeat(2048)),
    'not-an-asset.txt': Buffer.from('ignored')
  };
  for (const [name, buf] of Object.entries(fake)) fs.writeFileSync(path.join(dist, name), buf);
  const manifest = path.join(dist, gen.MANIFEST_NAME);

  console.log('release-checksums-smoke: generated bytes');
  const { assets } = gen.writeManifest(dist, manifest);
  const bytes = fs.readFileSync(manifest);
  const cr = [...bytes].filter((b) => b === 0x0D).length;
  const lf = [...bytes].filter((b) => b === 0x0A).length;
  check(assets.join(',') === '1132-Fixer-Portable-9.9.9.exe,1132-Fixer-Setup-9.9.9.exe', `only .exe assets, sorted by name (${assets.join(', ')})`);
  check(cr === 0, `CR byte count = ${cr}`);
  check(lf === 2, `LF separators present, one per record (${lf})`);
  check(!(bytes[0] === 0xEF && bytes[1] === 0xBB && bytes[2] === 0xBF), 'no UTF-8 BOM');
  check(bytes[bytes.length - 1] === 0x0A, 'final byte is LF');
  const lines = bytes.toString('utf8').split('\n').filter(Boolean);
  check(lines.length === 2, `two records (${lines.length})`);
  for (const line of lines) {
    const m = /^([0-9a-f]{64})  (\S.*)$/.exec(line);
    check(!!m, `record is "<64 hex>  <name>": ${line.slice(0, 20)}…`);
    if (m) check(gen.sha256File(path.join(dist, m[2])) === m[1], `hash matches ${m[2]}`);
  }
  const twice = gen.buildManifest(dist, gen.listAssets(dist));
  check(twice === bytes.toString('utf8'), 'regeneration is byte-identical (deterministic)');

  console.log('release-checksums-smoke: verifier accepts the generated manifest');
  const v = gen.verifyManifest(dist, manifest);
  check(v.ok, `verifyManifest ok (${v.errors.join('; ') || 'no errors'})`);
  check(v.report.crBytes === 0 && !v.report.bom && v.report.finalLf && v.report.entries === 2 && v.report.sorted && v.report.matched.length === 2,
    `report: CR=${v.report.crBytes} BOM=${v.report.bom} finalLF=${v.report.finalLf} entries=${v.report.entries} sorted=${v.report.sorted} matched=${v.report.matched.length}`);

  console.log('release-checksums-smoke: sha256sum -c on the unmodified file');
  const tool = findSha256sum();
  check(!!tool, `sha256sum available (${tool ? tool.cmd : 'not found'})`);
  if (tool) {
    const r = spawnSync(tool.cmd, [...tool.args, '-c', gen.MANIFEST_NAME], { cwd: dist, encoding: 'utf8' });
    check(r.status === 0, `sha256sum -c exit ${r.status}`);
    check(/Portable-9\.9\.9\.exe: OK/.test(r.stdout) && /Setup-9\.9\.9\.exe: OK/.test(r.stdout), `sha256sum reports OK for both assets`);
    // Negative control: the CRLF shape that shipped in 6.3.3 fails the same tool.
    const crlf = path.join(dist, 'crlf.txt');
    fs.writeFileSync(crlf, Buffer.from(bytes.toString('utf8').replace(/\n/g, '\r\n'), 'utf8'));
    const bad = spawnSync(tool.cmd, [...tool.args, '-c', 'crlf.txt'], { cwd: dist, encoding: 'utf8' });
    check(bad.status !== 0, `sha256sum -c rejects the CRLF manifest (exit ${bad.status})`);
  }

  console.log('release-checksums-smoke: verifier rejects bad manifests');
  const text = bytes.toString('utf8');
  const cases = {
    'CRLF line endings': text.replace(/\n/g, '\r\n'),
    'UTF-8 BOM': '\uFEFF' + text,
    'missing final LF': text.replace(/\n$/, ''),
    'wrong hash': text.replace(/^[0-9a-f]{64}/m, '0'.repeat(64)),
    'uppercase hash': text.replace(/^[0-9a-f]{64}/m, (h) => h.toUpperCase()),
    'single-space separator': text.replace('  ', ' '),
    'missing record': lines[0] + '\n',
    'unsorted': lines[1] + '\n' + lines[0] + '\n',
    'unknown asset': text + '0'.repeat(64) + '  ghost.exe\n'
  };
  for (const [label, content] of Object.entries(cases)) {
    const f = path.join(dist, 'bad-' + label.replace(/[^a-z]+/gi, '-') + '.txt');
    fs.writeFileSync(f, Buffer.from(content, 'utf8'));
    const r = gen.verifyManifest(dist, f);
    check(!r.ok, `rejects ${label}${r.ok ? '' : ' — ' + r.errors[0]}`);
  }

  console.log('release-checksums-smoke: workflows call the generator');
  const rel = fs.readFileSync(path.join(ROOT, '.github', 'workflows', 'release.yml'), 'utf8');
  const ci = fs.readFileSync(path.join(ROOT, '.github', 'workflows', 'ci.yml'), 'utf8');
  check(rel.includes('node scripts/generate-checksums.mjs --dist dist') && rel.includes('node scripts/generate-checksums.mjs --verify --dist dist'),
    'release.yml generates and verifies through scripts/generate-checksums.mjs');
  check(!/Out-File[^\n]*checksums|checksums[^\n]*Out-File|Set-Content[^\n]*checksums/.test(rel), 'release.yml has no other checksum writer');
  check(ci.includes('node scripts/generate-checksums.mjs --dist dist') && ci.includes('sha256sum -c checksums-sha256.txt'),
    'ci.yml exercises the same generator and runs sha256sum -c on its output');

  fs.rmSync(dist, { recursive: true, force: true });
  if (failures) {
    console.error(`release-checksums-smoke: ${failures} failure(s)`);
    process.exit(1);
  }
  console.log('release-checksums-smoke: all checks passed');
})().catch((e) => { console.error(e && e.stack || e); process.exit(1); });
