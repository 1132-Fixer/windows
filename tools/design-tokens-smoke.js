#!/usr/bin/env node
'use strict';

// Design tokens come from the design system, not from this repository.
// assets/design/tokens.css is an exact copy of css/tokens.windows.css at the
// pinned design-system commit. The :root block in index.html only gives those
// tokens short names. This smoke fails when a hand-copied value returns.
const assert = require('assert/strict');
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const read = (relative) => fs.readFileSync(path.join(root, relative), 'utf8').replace(/\r\n/g, '\n');
let checks = 0;
function check(condition, name) {
  assert.ok(condition, name);
  checks++;
  console.log(`  ok  ${name}`);
}

// Values that the design system has no token for yet. Each one is listed here
// on purpose; moving one into the design system removes it from this list.
const LOCAL_VALUES = Object.freeze({
  '--shadow-sm': '0 6px 14px rgba(8, 12, 24, 0.12)',
  '--shadow-md': '0 10px 22px rgba(8, 12, 24, 0.14)',
  '--shadow-lg': '0 14px 28px rgba(8, 12, 24, 0.16)',
  // Built only from two aliases in the same block.
  '--focus-ring': '0 0 0 2px var(--bg), 0 0 0 4px var(--focus)',
});
const TOKEN = /^var\((--[a-z0-9-]+)\)$/;
const TINT = /^color-mix\(in srgb, var\((--color-[a-z0-9-]+)\) (\d{1,2})%, transparent\)$/;

console.log('design-tokens-smoke: the shipped token file');
const tokensCss = read('assets/design/tokens.css');
check(tokensCss.startsWith('/* GENERATED by scripts/build-css.mjs.'), 'assets/design/tokens.css is the generated design-system file');
check(/^\/\* Product: windows\./m.test(tokensCss), 'it is the file for this product');
const defined = new Map([...tokensCss.matchAll(/^\s*(--[a-z0-9-]+):\s*([^;]+);$/gm)].map((match) => [match[1], match[2].trim()]));
check(defined.size >= 60, `it defines the design-system tokens (${defined.size})`);
const canonical = path.join(root, 'design-system', 'css', 'tokens.windows.css');
if (fs.existsSync(canonical)) {
  check(fs.readFileSync(canonical, 'utf8').replace(/\r\n/g, '\n') === tokensCss, 'the copy equals css/tokens.windows.css at the pinned design-system commit');
} else {
  console.log('  --  design-system submodule not checked out here; the brand-assets check compares the copy');
}
check(/^css\/tokens\.windows\.css\tassets\/design\/tokens\.css$/m.test(read('.brand-assets.tsv')), 'the brand-asset manifest maps the token file, so the brand guard compares it');

console.log('design-tokens-smoke: index.html states no token value of its own');
const page = read('index.html');
const link = page.indexOf('<link rel="stylesheet" href="assets/design/tokens.css">');
check(link > 0 && link < page.indexOf('<style>'), 'the token file is linked before the page styles');
const block = /:root\s*\{([\s\S]*?)\n\s{4}\}/.exec(page);
check(Boolean(block), 'the :root alias block is present');
check((page.match(/:root\s*\{/g) || []).length === 1, 'there is exactly one :root block');
const declarations = [...block[1].replace(/\/\*[\s\S]*?\*\//g, '').matchAll(/(--[a-z0-9-]+):\s*([^;]+);/g)].map((match) => [match[1], match[2].trim()]);
check(declarations.length >= 50, `the block declares the app aliases (${declarations.length})`);
const aliases = new Set(declarations.map(([name]) => name));
const problems = [];
let tokenAliases = 0;
let tints = 0;
for (const [name, value] of declarations) {
  if (Object.prototype.hasOwnProperty.call(LOCAL_VALUES, name)) {
    if (value !== LOCAL_VALUES[name]) problems.push(`${name}: local value changed; update LOCAL_VALUES on purpose`);
    continue;
  }
  const token = TOKEN.exec(value);
  const tint = TINT.exec(value);
  if (token) {
    if (!defined.has(token[1])) problems.push(`${name}: ${token[1]} is not a design-system token`);
    tokenAliases++;
  } else if (tint) {
    if (!defined.has(tint[1])) problems.push(`${name}: ${tint[1]} is not a design-system token`);
    tints++;
  } else {
    problems.push(`${name}: "${value}" is a value of its own; use a design-system token`);
  }
}
check(problems.length === 0, `every alias points at a design-system token${problems.length ? ': ' + problems.join(' | ') : ''}`);
check(tokenAliases >= 35 && tints === 10,`aliases: ${tokenAliases} direct, ${tints} tints mixed from a status colour`);
for (const name of Object.keys(LOCAL_VALUES)) check(aliases.has(name), `the listed local value ${name} is still in the block`);
check(!/#[0-9a-fA-F]{6}\b/.test(block[1].replace(/\/\*[\s\S]*?\*\//g, '')), 'no hex colour in the block');
check((page.match(/font-family:\s*var\(--font-sans\)/g) || []).length === 2 && !/font-family:\s*'Segoe UI/.test(page), 'the text font comes from the design system');
check(defined.get('--window-header') === '104px' && defined.get('--window-header-mark') === '80px' && defined.get('--window-footer') === '48px', 'the header, mark and footer sizes are the design-system window tokens');

console.log(`\ndesign-tokens-smoke: ${checks} checks passed`);
